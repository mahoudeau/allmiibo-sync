#!/usr/bin/env node
// Regenerates web/data/amiibo-db.js by merging two public sources.
//
//   node tools/build-amiibo-db.mjs <db_amiibo.c> [amiibo.json]
//
// Sources
// -------
// 1. solosky/pixl.js — fw/application/src/amiidb/db_amiibo.c
//    The table the device itself uses. Its names are more specific than
//    AmiiboAPI's ("[AC] 001 - Isabelle" rather than "Isabelle"), which matters
//    for a collection list: 67 of its names are ambiguous against 160 of
//    AmiiboAPI's.
//
// 2. N3evin/AmiiboAPI — database/amiibo.json (MIT)
//    Authoritative amiibo-series and figure-type labels, keyed by the series
//    and type bytes of the amiibo ID.
//
// Both currently carry an identical set of 932 IDs — the firmware table is an
// AmiiboAPI snapshot — so the merge is about label quality, not coverage.
//
// Vendored deliberately: nothing is fetched at runtime.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const [firmwareSrc, apiSrc] = process.argv.slice(2);
if (!firmwareSrc) {
  console.error('usage: node tools/build-amiibo-db.mjs <db_amiibo.c> [amiibo.json]');
  process.exit(1);
}

// ---- names from the firmware table --------------------------------------

const c = await readFile(firmwareSrc, 'utf8');
// {0x01810001, 0x00440502, "[AC] 001 - Isabelle", "..."},
const row = /\{\s*0x([0-9a-fA-F]{8})\s*,\s*0x([0-9a-fA-F]{8})\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\}/g;

const names = new Map();
for (const m of c.matchAll(row)) {
  names.set(`${m[1].toLowerCase()}${m[2].toLowerCase()}`, m[3].replace(/\\"/g, '"'));
}

// ---- series and type labels from AmiiboAPI ------------------------------

let series = {};
let types = {};
let apiCount = 0;

if (apiSrc) {
  const api = JSON.parse(await readFile(apiSrc, 'utf8'));
  const byte = (k) => parseInt(k.replace(/^0x/, ''), 16);

  for (const [k, v] of Object.entries(api.amiibo_series ?? {})) series[byte(k)] = v;
  for (const [k, v] of Object.entries(api.types ?? {})) types[byte(k)] = v;

  // Fill any gap the firmware table does not cover.
  for (const [k, v] of Object.entries(api.amiibos ?? {})) {
    const id = k.replace(/^0x/, '').toLowerCase();
    apiCount++;
    if (!names.has(id)) names.set(id, v.name);
  }
}

const sortNum = (o) =>
  Object.fromEntries(Object.entries(o).map(([k, v]) => [Number(k), v]).sort((a, b) => a[0] - b[0]));
series = sortNum(series);
types = sortNum(types);

const entries = [...names].sort((a, b) => a[0].localeCompare(b[0]));

const out = `// Generated by tools/build-amiibo-db.mjs — do not edit by hand.
//
// Sources:
//   - solosky/pixl.js  fw/application/src/amiidb/db_amiibo.c   (names)
//   - N3evin/AmiiboAPI database/amiibo.json, MIT               (series, types)
//
// ${entries.length} amiibo IDs, ${Object.keys(series).length} series, ${Object.keys(types).length} types.

// amiibo ID (16 hex chars, bytes 84..91 of a dump) -> display name.
export const AMIIBO_NAMES = Object.freeze({
${entries.map(([id, name]) => `  '${id}': ${JSON.stringify(name)},`).join('\n')}
});

// Byte 6 of the ID -> amiibo series.
export const AMIIBO_SERIES = Object.freeze({
${Object.entries(series).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')}
});

// Byte 3 of the ID -> figure type.
export const AMIIBO_TYPES = Object.freeze({
${Object.entries(types).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')}
});
`;

const dest = join(fileURLToPath(new URL('..', import.meta.url)), 'web/data/amiibo-db.js');
await writeFile(dest, out);
console.log(
  `wrote ${entries.length} names, ${Object.keys(series).length} series, ` +
    `${Object.keys(types).length} types (AmiiboAPI contributed ${apiCount} entries)`
);
