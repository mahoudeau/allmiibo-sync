#!/usr/bin/env node
// Regenerates CHANGELOG.md from web/data/changelog.js.
//
//   npm run build-changelog
//
// The data file is the only place entries are written. The site renders it
// directly; this turns the same data into markdown for anyone reading the
// repository. test/changelog.test.mjs regenerates and compares, so an edit to
// one that misses the other fails the suite rather than drifting quietly.
//
// The one difference between the two outputs is `internal`: the admin service
// and the database tooling are not part of the site anyone visits, so they are
// noise on the page and a lie by omission if left out of the repo's history.
// They land here under "Behind the scenes" and nowhere else.
//
// Like build-amiibo-db.mjs, this is a CLI and a library: `render()` returns the
// file contents and touches no disk, so the test can call it directly.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { RELEASES, CATEGORIES, INTERNAL } from '../web/data/changelog.js';

const OUT = new URL('../CHANGELOG.md', import.meta.url);

const HEADER = `<!-- Generated by tools/build-changelog.mjs. Do not edit by hand.
     Entries live in web/data/changelog.js, which also feeds the site's
     What's New page. Run \`npm run build-changelog\` after changing it. -->

# Changelog

Every release of [allmiibo-sync](https://allmiibo.mathieu.dev), newest first.
The same history, minus the sections that only concern this repository, is on
the site under [What's new](https://allmiibo.mathieu.dev/changelog.html).
`;

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December'];

function formatDate(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

// Entries are plain strings, or { group, items }. Markdown takes both as they
// are, since the inline syntax the data uses is already markdown.
function section(items) {
  const out = [];
  for (const item of items) {
    if (typeof item === 'string') out.push(`- ${item}`);
    else {
      out.push('', `#### ${item.group}`, '');
      for (const line of item.items) out.push(`- ${line}`);
    }
  }
  return out.join('\n');
}

export function render(releases = RELEASES) {
  const parts = [HEADER];

  for (const release of releases) {
    parts.push(`\n## ${release.version} · ${formatDate(release.date)}\n`);
    parts.push(`**${release.title}**\n`);

    for (const cat of [...CATEGORIES, INTERNAL]) {
      const items = release[cat.key];
      if (!items?.length) continue;
      parts.push(`### ${cat.label}\n`);
      parts.push(`${section(items)}\n`);
    }
  }

  // One trailing newline, so the file ends the way every other text file does.
  return `${parts.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

// CLI only when run directly, so importing this for the test writes nothing.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(OUT, render(), 'utf8');
  const count = RELEASES.length;
  console.log(`CHANGELOG.md written: ${count} release${count === 1 ? '' : 's'}, ` +
    `newest ${RELEASES[0].version}.`);
}
